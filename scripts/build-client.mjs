#!/usr/bin/env node
/**
 * Build the DSH browser bundle: src/client.core.js -> lib/client.js
 *
 * DSH serves the built file verbatim at `/plugins/dsh-pet-astra-yao/client.js`,
 * so the bundle is committed. The wrapper is the documented client-module
 * format: `window.__ModuleLoader__.load({ id, factory })`, where the factory
 * receives the module `require` and returns the plugin exports.
 *
 * The script also injects the shared atlas description (src/atlas.js) and the
 * package version, so the browser half can never drift from the host half.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { describeAtlas } from '../src/atlas.js'

const root = new URL('..', import.meta.url)

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? pad + line : line))
    .join('\n')
}

const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'))
const rawCore = await readFile(new URL('src/client.core.js', root), 'utf8')
const core = rawCore.replace(/\r\n/gu, '\n').trimEnd()
const atlas = describeAtlas()

const banner = [
  `/* dsh-pet-astra-yao v${pkg.version} - DeepSeek Harness browser bundle.`,
  ' * Generated by scripts/build-client.mjs from src/client.core.js.',
  ' * Do not edit this file; edit the source and run `npm run build`.',
  ' */',
].join('\n')

/**
 * Escape every non-ASCII code unit. The host serves this file verbatim and the
 * browser decodes `<script>` without an explicit charset, so ASCII-only output
 * keeps the Chinese menu labels intact even if the transport guesses wrong.
 */
function escapeNonAscii(text) {
  return text.replace(/[^\x00-\x7f]/gu, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`)
}

const output = escapeNonAscii(`${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    'use strict';
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });
    const PET_ATLAS = ${JSON.stringify(atlas)};
    const PET_VERSION = ${JSON.stringify(pkg.version)};
${indent(core, 4)}
    return module.exports;
  },
});
`)

const target = new URL('lib/client.js', root)
await mkdir(new URL('lib/', root), { recursive: true })
await writeFile(target, output, 'utf8')

const frames = Object.entries(atlas.animations)
  .map(([name, animation]) => `${name}(row ${animation.row}, ${animation.frames}f)`)
  .join(', ')

console.log(`built lib/client.js — ${Buffer.byteLength(output)} bytes`)
console.log(`  atlas ${atlas.sheetWidth}x${atlas.sheetHeight}, ${atlas.columns}x${atlas.rows} frames of ${atlas.frameWidth}x${atlas.frameHeight}`)
console.log(`  animations: ${frames}`)
